/** Verify committed trace contracts and the Rust tables generated from them. */
import { parseTraceArtifact, type TraceArtifact, type TraceRequest } from '../src/lib/traces'
import {
  SCHED_REQUESTS,
  checkSchedBand,
  drawSchedTrace,
  makeSchedTrace,
  measureAcceptance,
  minuteSampleLine,
  minuteSourceCount,
  parseSchedSource,
  practiceMinute,
} from '../src/lib/world/sched-traces'

const ROOT = new URL('../', import.meta.url)
const paths = {
  kimi: new URL('public/traces/kimi-conversation.json', ROOT),
  burst: new URL('public/traces/burstgpt-v2-busiest-hour.json', ROOT),
  minute: new URL('public/traces/burstgpt-v2-busiest-minute.json', ROOT),
  lmsys: new URL('public/traces/lmsys-chat-1m-published-shape.json', ROOT),
  rust: new URL('labs/batching-scheduler/src/trace_scenarios.rs', ROOT),
}

async function artifact(url: URL): Promise<TraceArtifact> {
  const raw = await Bun.file(url).json()
  const parsed = await parseTraceArtifact(raw)
  for (const [index, row] of parsed.requests.entries()) {
    const keys = Object.keys(row).sort().join(',')
    if (keys !== 'o,p,t') throw new Error(`${parsed.id} row ${index} exposes fields beyond t/p/o`)
  }
  return parsed
}

function mean(rows: TraceRequest[], key: 'p' | 'o'): number {
  return rows.reduce((sum, row) => sum + row[key], 0) / rows.length
}

function rustRows(name: string, rows: TraceRequest[]): string {
  return `pub const ${name}: &[(u32, u32, u32)] = &[\n${rows
    .map((row) => `    (${row.t}, ${row.p}, ${row.o}),\n`)
    .join('')}];\n`
}

const [kimi, burst, lmsys] = await Promise.all([
  artifact(paths.kimi),
  artifact(paths.burst),
  artifact(paths.lmsys),
])

if (kimi.kind !== 'recorded' || kimi.requestCount !== 1200) throw new Error('Kimi contract drifted')
if (burst.kind !== 'recorded' || burst.requestCount !== 480 || burst.license !== 'CC-BY-4.0') {
  throw new Error('BurstGPT contract drifted')
}
if (lmsys.kind !== 'synthetic-profile' || lmsys.requestCount !== 360) {
  throw new Error('LMSYS profile must remain synthetic and contain 360 rows')
}
if (mean(lmsys.requests, 'p') !== 69.5 || mean(lmsys.requests, 'o') !== 214.5) {
  throw new Error('LMSYS published aggregate means drifted')
}

/** The scheduler play's practice minute, pinned: a rebuild from a different source or sampling changes these. */
const SCHED_ACCEPTANCE_TARGET_PCT = 20
/** Below this the draw loop would need more than MAX_DRAWS candidates too often. */
const SCHED_ACCEPTANCE_FLOOR_PCT = 1
const MINUTE = {
  requestSha256: '945c778b35066571a3354a7912c49503201d6473e825e5d2080365afa03a9db9',
  sourceWindowStart: 3063960,
  sourceRowsInWindow: 1095,
}
const minute = await artifact(paths.minute)
const minuteSampling = minute.sampling
if (minute.kind !== 'recorded' || minute.requestCount !== SCHED_REQUESTS || minute.license !== 'CC-BY-4.0') {
  throw new Error('BurstGPT busiest-minute contract drifted')
}
if (minute.sourceSha256 !== burst.sourceSha256) throw new Error('the minute and the hour come from different BurstGPT sources')
if (minute.requestSha256 !== MINUTE.requestSha256) throw new Error(`busiest-minute requestSha256 drifted: ${minute.requestSha256}`)
if (
  minuteSampling.windowSeconds !== 60 ||
  minuteSampling.secondsPerTick !== 1 ||
  minuteSampling.selectedRows !== SCHED_REQUESTS ||
  minuteSampling.sourceWindowStart !== MINUTE.sourceWindowStart ||
  minuteSourceCount(minute) !== MINUTE.sourceRowsInWindow
) {
  throw new Error('busiest-minute sampling record drifted')
}
if (minute.requests.some((row) => row.t > 59)) throw new Error('a busiest-minute arrival falls outside the 60 s window')

const expectedRust =
  '//! Generated by scripts/build-traces.py; do not edit by hand.\n' +
  '//! These tables mirror public/traces exactly.\n\n' +
  rustRows('BURSTGPT_REQUESTS', burst.requests) +
  '\n' +
  rustRows('LMSYS_SHAPE_REQUESTS', lmsys.requests)
const actualRust = await Bun.file(paths.rust).text()
if (actualRust !== expectedRust) throw new Error('Rust trace tables do not match the public artifacts')

for (const item of [kimi, burst, minute, lmsys]) {
  console.log(
    `${item.id.padEnd(39)} ${String(item.requestCount).padStart(4)} rows · ` +
      `p̄ ${mean(item.requests, 'p').toFixed(1).padStart(6)} · ` +
      `ō ${mean(item.requests, 'o').toFixed(1).padStart(6)} · ${item.kind}`,
  )
}

// The scheduler play's traces: the band on the practice minute, and how often a fresh minute is in band.
const source = await parseSchedSource(await Bun.file(paths.minute).json(), await Bun.file(paths.burst).json())
console.log(`\n${minuteSampleLine(source.minute)}`)
const practice = checkSchedBand(practiceMinute(source))
console.log(
  `practice minute: ghost ${practice.ghost.met}/${practice.ghost.total} within SLO, ${practice.ghost.turns} turns, ` +
    `${practice.ghost.iterations} iterations; band rules ${practice.rules.map((ok, i) => `${i + 1}${ok ? '+' : '-'}`).join(' ')}` +
    (practice.inBand ? '' : ` (not in band: ${practice.violations.join('; ')})`),
)
const ACCEPTANCE_SEEDS = 2000
const acceptance = measureAcceptance(source, ACCEPTANCE_SEEDS)
console.log(
  `fresh-minute band acceptance: ${(acceptance.rate * 100).toFixed(2)} % of ${ACCEPTANCE_SEEDS} seeds ` +
    `(${acceptance.inBand} in band; rejected by rule 1-5: ${acceptance.rejectedBy.join(', ')}; ` +
    `spec target ${SCHED_ACCEPTANCE_TARGET_PCT} %)`,
)
if (acceptance.rate * 100 < SCHED_ACCEPTANCE_FLOOR_PCT) {
  throw new Error(`fresh-minute acceptance fell below ${SCHED_ACCEPTANCE_FLOOR_PCT} %: the band no longer fits the generator`)
}
for (const entropy of [0, 1, 0x5eed, 0xdeadbeef]) {
  const draw = drawSchedTrace(entropy, source)
  const again = drawSchedTrace(entropy, source)
  if (JSON.stringify(draw.trace) !== JSON.stringify(again.trace)) throw new Error(`drawSchedTrace(${entropy}) is not deterministic`)
  if (!draw.band.inBand) throw new Error(`drawSchedTrace(${entropy}) returned a minute outside the band`)
  if (JSON.stringify(makeSchedTrace(source, draw.trace.seed as number)) !== JSON.stringify(draw.trace)) {
    throw new Error(`drawSchedTrace(${entropy}) is not makeSchedTrace of its own seed`)
  }
}

console.log('OK: provenance schema, checksums, privacy surface, and Rust tables verified')
